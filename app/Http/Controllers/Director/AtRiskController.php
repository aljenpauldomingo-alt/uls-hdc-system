<?php

namespace App\Http\Controllers\Director;

use App\Enums\FollowUpStatus;
use App\Http\Controllers\Controller;
use App\Models\AccessLog;
use App\Models\User;
use App\Support\AtRiskQuery;
use App\Support\Form5;
use App\Support\Form8;
use App\Support\Reports\ReportFilters;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Validation\Rule;
use Illuminate\View\View;
use Symfony\Component\HttpFoundation\StreamedResponse;

/**
 * Director-only list of students who reported (Form 5) or were found (Form 8) to have at least one
 * psychological concern, with follow-up tracking. Every view, export and follow-up change is logged.
 */
class AtRiskController extends Controller
{
    public function index(Request $request): View
    {
        $query = AtRiskQuery::fromRequest($request);
        $students = $query->paginate($request);

        $this->log($request, AccessLog::ACTION_VIEW_AT_RISK, 'results: '.$students->total());

        return view('director.at-risk.index', [
            'query' => $query,
            'filters' => $query->filters(),
            'scope' => $query->scope,
            'students' => $students,
            'summary' => $query->summary(),
            'schoolYears' => ReportFilters::schoolYearOptions(),
        ]);
    }

    /**
     * CSV of the current filtered list. Never includes the director's follow-up notes.
     */
    public function export(Request $request): StreamedResponse
    {
        $query = AtRiskQuery::fromRequest($request);
        $rows = $query->results();

        $this->log($request, AccessLog::ACTION_EXPORT_AT_RISK, 'format: csv; students: '.$rows->count());

        $user = $request->user();
        $filename = 'hdc-at-risk-'.now(config('hdc.local_timezone'))->format('Y-m-d').'.csv';

        return response()->streamDownload(function () use ($rows, $user): void {
            $out = fopen('php://output', 'w');
            $write = fn (array $row) => fputcsv($out, array_map(self::csvCell(...), $row), escape: '');

            $write(['ULS Human Development Center: At Risk students (CONFIDENTIAL)']);
            $write(['Generated', now(config('hdc.local_timezone'))->format('Y-m-d H:i')]);
            $write(['Generated by', $user->name.' ('.$user->role->label().')']);
            $write([]);
            $write(['Last name', 'First name', 'Middle name', 'Student no.', 'Program', 'College', 'Year level', 'Student type',
                'Concerns', 'Urgent', 'Source', 'Intake status', 'Latest date', 'Follow-up status', 'Follow-up updated']);

            foreach ($rows as $row) {
                $student = $row->student;
                $write([
                    $student->last_name, $student->first_name, $student->middle_name, $student->student_number,
                    $student->program?->code, $student->program?->college?->code,
                    Form5::YEAR_LEVELS[$student->year_level] ?? '',
                    Form5::STUDENT_TYPES[$row->student_type] ?? '',
                    implode('; ', Form5::labels(Form8::CONCERNS, $row->concerns)),
                    $row->urgent ? 'Yes' : 'No',
                    AtRiskQuery::SOURCES[$row->source],
                    $row->intake_status?->label() ?? 'None',
                    $row->latest_date?->setTimezone(config('hdc.local_timezone'))->format('Y-m-d') ?? '',
                    $row->follow_up_status->label(),
                    $row->follow_up?->updated_at?->setTimezone(config('hdc.local_timezone'))->format('Y-m-d H:i') ?? '',
                ]);
            }

            fclose($out);
        }, $filename, ['Content-Type' => 'text/csv; charset=UTF-8']);
    }

    public function updateFollowUp(Request $request, User $student): RedirectResponse
    {
        abort_unless($student->isStudent(), 404);

        $validated = $request->validate([
            'status' => ['required', Rule::enum(FollowUpStatus::class)],
            'note' => ['nullable', 'string', 'max:2000'],
        ]);

        $followUp = $student->followUp()->firstOrNew();
        $previous = $followUp->exists ? $followUp->status : FollowUpStatus::New;
        $followUp->fill($validated);
        $followUp->updated_by = $request->user()->id;
        $followUp->save();

        // The note is private: only the status change is written to the log.
        $this->log($request, AccessLog::ACTION_UPDATE_FOLLOW_UP,
            "student: {$student->id}; status: {$previous->value} -> {$followUp->status->value}",
            $student->latestCumulativeRecord?->id);

        return back()->with('status', __('Follow-up for :name saved.', ['name' => $student->name]));
    }

    private function log(Request $request, string $action, string $details, ?int $recordId = null): void
    {
        AccessLog::create([
            'user_id' => $request->user()->id,
            'cumulative_record_id' => $recordId,
            'action' => $action,
            'details' => mb_substr($details, 0, 500),
            'ip' => $request->ip(),
        ]);
    }

    /**
     * Stop spreadsheet programs from running a cell as a formula.
     */
    private static function csvCell(?string $value): string
    {
        $value = (string) $value;

        return $value !== '' && in_array($value[0], ['=', '+', '-', '@', "\t", "\r"], true) ? "'".$value : $value;
    }
}
